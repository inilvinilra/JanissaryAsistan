export function translate(locale: Locale, key: string, vars?: Record<string, string>): string {
  let text = dictionaries[locale][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v);
  }
  return text;
}

export function categoryLabel(locale: Locale, category: string): string {
  return categoryLabels[locale][category] ?? category;
}
